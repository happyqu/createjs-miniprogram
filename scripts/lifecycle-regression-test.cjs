const assert = require('node:assert/strict');
require('./helpers/mock-canvas.cjs')();
const c = require('../dist/lite.js');
require('../dist/lite-animation.js');
const SceneSession = require('../example/utils/scene-session');
const a = new SceneSession(c,()=>{}), b = new SceneSession(c,()=>{});
a.setActive(true); b.setActive(true);
const ta=a.tween({x:0}).to({x:1},100), tb=b.tween({x:0}).to({x:1},100);
a.setActive(false);
assert.equal(ta.paused,true); assert.equal(tb.paused,false);
const hidden=a.tween({x:0}).to({x:1},100);
assert.equal(hidden.paused,true);
a.setActive(true); assert.equal(ta.paused,false); assert.equal(hidden.paused,false);
a.clearTweens(); assert.equal(tb.paused,false);
a.dispose(); b.dispose(); c.Ticker.reset();

let page;
global.Page = spec => {page=spec;};
require('../example/pages/index/index.js');
page.session = {setActive() {}, dispose() {}};
page.stage = {__touch:null, dispose() {}};
page.onHide(); page.onShow(); page.onUnload();
assert.equal(page.stage,null); assert.equal(page.unloaded,true);
require('../example/pages/benchmark/benchmark.js');
page.session = {setActive() {}, dispose() {}};
page.stage = {dispose() {}};
page.onHide(); page.onUnload();
assert.equal(page.stage,null); assert.equal(page.unloaded,true);
console.log('Page lifecycle and tween isolation checks passed');
